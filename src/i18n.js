function pack(lang) { return STRINGS[lang] || STRINGS.en; }

function t(lang, key, vars = {}) {
  const p = pack(lang);
  const [group, k] = key.split('.');
  let s = (p[group] && p[group][k]) ?? (STRINGS.en[group] && STRINGS.en[group][k]) ?? key;
  for (const [n, v] of Object.entries(vars)) s = s.split(`{${n}}`).join(String(v));
  return s;
}

